// Builds one file with every environment variable for Vercel: .env.vercel (git-ignored).
// Run on your own computer: node scripts/make-vercel-env.js
// Then in Vercel: Project, Settings, Environment Variables, drag the file in (or Import .env).
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = path.join(__dirname, '..');
const j = JSON.parse(fs.readFileSync(path.join(root, 'firebase-service-account.json'), 'utf8'));
const local = {};
try { fs.readFileSync(path.join(root, '.env.local'), 'utf8').split(/\r?\n/).forEach(l => { const m = l.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/); if (m) local[m[1]] = m[2].replace(/^"(.*)"$/, '$1'); }); } catch (e) { /* none */ }
const lines = [
  '# Generated by scripts/make-vercel-env.js. Contains secrets: never commit or share this file.',
  'FIREBASE_PROJECT_ID=' + j.project_id,
  'FIREBASE_CLIENT_EMAIL=' + j.client_email,
  'FIREBASE_PRIVATE_KEY=' + JSON.stringify(j.private_key), // one line, quotes kept, newlines written as \n
  'FIREBASE_STORAGE_BUCKET=' + (local.FIREBASE_STORAGE_BUCKET || j.project_id + '.firebasestorage.app'),
  'AUTH_SECRET=' + (local.AUTH_SECRET || crypto.randomBytes(32).toString('hex')),
  'ADMIN_EMAIL=' + (local.ADMIN_EMAIL || 'uokmun4@gmail.com'),
  'NEXT_PUBLIC_SITE_URL=https://uok-mun.vercel.app'
];
Object.keys(local).filter(k => k.startsWith('NEXT_PUBLIC_FIREBASE_')).forEach(k => lines.push(k + '=' + local[k]));
fs.writeFileSync(path.join(root, '.env.vercel'), lines.join('\n') + '\n');
console.log('Written .env.vercel with these variables:\n' + lines.filter(l => !l.startsWith('#')).map(l => ' - ' + l.split('=')[0]).join('\n'));
